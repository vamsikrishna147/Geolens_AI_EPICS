"""
GeoLens AI - Temporal Analysis Agent (TimeLens Engine)
======================================================
The Temporal Analysis Agent is the core intelligence behind TimeLens historical
change detection. It analyzes multi-temporal satellite datasets, GEE metrics,
and zonal statistics to quantify land cover dynamics, urban sprawl, deforestation,
and disaster progression between baseline and current years.

Position in pipeline:
  Planner -> Dataset Discovery -> Data Acquisition -> GIS Processing -> Temporal Analysis (TimeLens) -> Satellite Analysis -> Recommendation -> Official Report
"""

import os
from crewai import Agent, LLM

from tools.gee_tool import GEETool
from tools.raster_tool import RasterTool
from tools.vector_tool import VectorTool
from tools.map_tool import MapTool
from tools.change_detection_tool import ChangeDetectionTool


def create_temporal_analysis_agent(llm: LLM = None) -> Agent:
    """
    Create and return the Temporal Analysis Agent (TimeLens Engine).

    Args:
        llm: Optional LLM instance. Defaults to Gemini from env.

    Returns:
        A configured CrewAI Agent with GEE, Raster, Vector, and Map tools.
    """
    if llm is None:
        llm = LLM(
            model=os.getenv("GEMINI_MODEL", "gemini/gemini-2.0-flash"),
            api_key=os.getenv("GEMINI_API_KEY"),
            temperature=0.2,  # Low temperature for analytical precision
        )

    tools = [
        ChangeDetectionTool(),  # Primary Phase 4 engine: all spectral pipelines (NDVI, NDWI, SAR, NBR, CVA)
        GEETool(),              # GEE satellite data + change_detection & nbr analysis branches
        RasterTool(),           # Local raster ops: difference, ndvi, ndwi, nbr, transition_matrix
        VectorTool(),           # Vector spatial analysis
        MapTool(),              # Interactive HTML map generation
    ]

    agent = Agent(
        role="TimeLens Historical Change Detection & Multi-Temporal Analyst",
        goal=(
            "Quantify and explain multi-temporal environmental and infrastructure changes "
            "between baseline historical years (e.g., 2018-2020) and recent/current periods (e.g., 2024-2025). "
            "Analyze optical/SAR imagery differencing, NDVI/NDWI trend metrics, urban expansion rates, "
            "forest loss, surface water contraction/expansion, and disaster impacts. Provide exact quantitative "
            "metrics (area in sq km, percentage change) and clear natural language explanations of what changed, "
            "why it changed, and what physical processes drove the transformation."
        ),
        backstory=(
            "You are a world-renowned Senior Remote Sensing Specialist and Computer Vision Lead specializing in "
            "multi-temporal satellite image analysis, Change Vector Analysis (CVA), and Earth observation metrics.\n\n"
            "You are the core intelligence behind GeoLens AI's signature engine: **TimeLens**.\n\n"
            "Your Expertise:\n"
            "- **Urban Expansion**: Quantifying built-up area growth, infrastructure expansion, and agricultural conversion.\n"
            "- **Deforestation & Canopy Loss**: Calculating loss of dense forest cover, canopy fragmentation, and vegetation index decline (NDVI).\n"
            "- **Water-Body Dynamics**: Tracking reservoir depletion, river course shifts, coastal erosion, and flood inundation evolution (NDWI & SAR VV/VH thresholds).\n"
            "- **Disaster Impact Progression**: Comparing pre-disaster vs. post-disaster satellite passes to calculate net spatial damage.\n\n"
            "Your Methodology:\n"
            "1. Identify the baseline period (T1) and comparison period (T2) from the Planner Agent's output.\n"
            "2. Examine raster outputs, GEE data, and zonal statistics generated by upstream tools.\n"
            "3. Compute net delta values: Area T1 (sq km) vs Area T2 (sq km), Percentage Change (%), and Direction of Change.\n"
            "4. Classify changes into standardized categories (Vegetation Loss, Urban Sprawl, Inundation, Land Degradation).\n"
            "5. Produce a sharp, evidence-based TimeLens brief that synthesizes the physical transformation."
        ),
        tools=tools,
        llm=llm,
        verbose=True,
        allow_delegation=False,
        max_iter=20,
    )

    return agent
